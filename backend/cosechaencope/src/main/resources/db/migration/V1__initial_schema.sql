-- 1. Tabla de usuarios
CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(255),
    tipo_usuario VARCHAR(255) NOT NULL
);

-- 2. Tabla de clientes
CREATE TABLE IF NOT EXISTS cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT UNIQUE,
    nombre VARCHAR(255),
    direccion VARCHAR(255),
    telefono VARCHAR(255),
    fecha_registro TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_cliente_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_cliente_id_usuario ON cliente (id_usuario);

-- 3. Tabla de productores
CREATE TABLE IF NOT EXISTS productor (
    id_productor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT UNIQUE,
    nombre VARCHAR(255),
    direccion VARCHAR(255),
    telefono VARCHAR(255),
    imagen_url VARCHAR(255),
    fecha_registro TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_productor_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_productor_id_usuario ON productor (id_usuario);

-- 4. Tabla de categorías
